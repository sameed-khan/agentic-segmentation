"""Generate research/experiments/TABLES.md from the exported (git-tracked) run records.

    uv run --project harness/server python eval/v2/build_log_tables.py

Inputs: research/experiments/runs/<run_id>/ (written by eval/v2/export_run.py) and
eval/v2/mstt_cases.csv. Nothing here reads results/ or GT, so the tables are reproducible from git alone.
The narrative experiment log (research/experiment_log.md) cites these tables.
"""
from __future__ import annotations

import csv
import json
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUNS = ROOT / "research" / "experiments" / "runs"
OUT = ROOT / "research" / "experiments" / "TABLES.md"
HTYPES = ["F", "L", "M", "N", "V"]
UNET = {"F": 0.507, "L": 0.744, "M": 0.823, "N": 0.748, "V": 0.584}


def design_cases() -> list[dict]:
    rows = list(csv.DictReader(open(ROOT / "eval" / "v2" / "mstt_cases.csv", newline="")))
    return [{k.strip(): (v or "").strip() for k, v in r.items()} for r in rows if (r.get("split") or "").strip() == "design"]


def f3(x) -> str:
    try:
        return f"{float(x):.3f}"
    except (TypeError, ValueError):
        return "–"


def mean_med(vals):
    vals = [v for v in vals if v is not None]
    return (st.mean(vals), st.median(vals)) if vals else (float("nan"), float("nan"))


def phase1_runs() -> list[str]:
    out = []
    for d in sorted(RUNS.iterdir()):
        if (d / "batch_summary.json").exists() and (d / "scores.csv").exists():
            n = len(list(csv.DictReader(open(d / "scores.csv"))))
            if n == 30:
                out.append(d.name)
    return out


def main() -> None:
    cases = design_cases()
    by_case = {c["case"]: c for c in cases}
    L: list[str] = ["# Experiment tables (generated)", "",
                    "Generated by `eval/v2/build_log_tables.py` from `research/experiments/runs/` (git). "
                    "Do not edit by hand. Narrative and decisions: `research/experiment_log.md`.", ""]

    # --- design cases
    L += ["## 1. Design split (30 cases)", "", "| case | histotype | sequence |", "|---|---|---|"]
    L += [f"| {c['case']} | {c['histotype']} | {c['sequence']} |" for c in cases]
    L.append("")

    # --- one-click baseline
    oc = {r["case"]: r for r in csv.DictReader(open(RUNS / "oneclick_design" / "results.csv"))}
    occ = {r["case"]: r for r in csv.DictReader(open(RUNS / "oneclick_design_colab" / "results.csv"))}
    L += ["## 2. One-click nnInteractive baseline (oracle seed = GT largest-component centroid, no LLM)", "",
          "Runs: `oneclick_design` (A10 dev server, reference) and `oneclick_design_colab` (Colab L4, first run).", "",
          "| histotype | n | mean Dice (A10) | median | mean Dice (Colab) | published U-Net mean |", "|---|---|---|---|---|---|"]
    for h in HTYPES:
        a = [float(r["dice_all"]) for r in oc.values() if r["histotype"] == h]
        b = [float(r["dice_all"]) for r in occ.values() if r["histotype"] == h]
        L.append(f"| {h} | {len(a)} | {st.mean(a):.3f} | {st.median(a):.3f} | {st.mean(b):.3f} | {UNET[h]:.3f} |")
    a = [float(r["dice_all"]) for r in oc.values()]
    b = [float(r["dice_all"]) for r in occ.values()]
    L += [f"| **all** | {len(a)} | {st.mean(a):.3f} | {st.median(a):.3f} | {st.mean(b):.3f} | 0.681 |", ""]
    L += ["| case | Dice (A10) | Dice (Colab) | pred mL | GT mL | pred components |", "|---|---|---|---|---|---|"]
    for c in cases:
        r = oc.get(c["case"], {})
        L.append(f"| {c['case']} | {f3(r.get('dice_all'))} | {f3(occ.get(c['case'], {}).get('dice_all'))} | "
                 f"{r.get('pred_ml', '–')} | {r.get('gt_ml', '–')} | {r.get('pred_components', '–')} |")
    L.append("")

    # --- Phase 2
    p2 = [d.name for d in sorted(RUNS.iterdir()) if (d / "score.json").exists() and (d / "scored.jsonl").exists()
          and not d.name.endswith("smoke2")]
    L += ["## 3. Phase 2 localization study (single-turn, design cases)", ""]
    for run in p2:
        sc = json.loads((RUNS / run / "score.json").read_text())
        meta = json.loads((RUNS / run / "meta.json").read_text())
        L += [f"### {run} (model {meta.get('model')}, thinking {meta.get('thinking')}, reps {meta.get('reps')})", "",
              "| condition | calls | hit rate (mean over reps) | majority hit/case | dist mean mm | parse fail | invalid |",
              "|---|---|---|---|---|---|---|"]
        for cond, v in sc["aggregate"].items():
            if not isinstance(v, dict) or "hit_rate_mean_over_reps" not in v:
                continue
            L.append(f"| {cond} | {v['n_calls']} | {v['hit_rate_mean_over_reps']:.3f} | {v['majority_hit_rate_per_case']:.3f} | "
                     f"{v['distance_mean_mm']:.1f} | {v['n_parse_fail']} | {v['n_invalid_mark']} |")
        recs = [json.loads(l) for l in open(RUNS / run / "scored.jsonl")]
        conds = sorted({r["condition"] for r in recs})
        L += ["", "Per histotype (hit rate):", "", "| histotype | " + " | ".join(conds) + " |",
              "|---|" + "---|" * len(conds)]
        for h in HTYPES:
            cells = []
            for cnd in conds:
                hs = [1.0 if r.get("hit") else 0.0 for r in recs if r["condition"] == cnd and by_case.get(r["case"], {}).get("histotype") == h]
                cells.append(f"{st.mean(hs):.3f}" if hs else "–")
            L.append(f"| {h} | " + " | ".join(cells) + " |")
        L += ["", "Per case (hits / reps):", "", "| case | " + " | ".join(conds) + " |", "|---|" + "---|" * len(conds)]
        for c in cases:
            cells = []
            for cnd in conds:
                hs = [r for r in recs if r["condition"] == cnd and r["case"] == c["case"]]
                cells.append(f"{sum(1 for r in hs if r.get('hit'))}/{len(hs)}" if hs else "–")
            L.append(f"| {c['case']} | " + " | ".join(cells) + " |")
        L.append("")

    # --- Phase 1
    runs = phase1_runs()
    L += ["## 4. Phase 1 agent passes (30 design cases each)", "",
          "| run | started | model | thinking | git / harness sha256 | mean Dice | median | mean Dice localized | n localized | "
          "localization fails | tool calls (mean) | model prompts (mean) | harness errors | forced finishes | cost USD |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    data = {}
    for run in runs:
        bs = json.loads((RUNS / run / "batch_summary.json").read_text())
        sc = {r["case"]: r for r in csv.DictReader(open(RUNS / run / "scores.csv"))}
        data[run] = sc
        dice = [float(r["dice"]) for r in sc.values()]
        loc = [r for r in sc.values() if r["tag"] != "localization"]
        dl = [float(r["dice"]) for r in loc]
        tc = [int(r["n_tool_calls"]) for r in sc.values()]
        mp = [int(r["n_model_prompts"]) for r in sc.values()]
        herr = sum(1 for r in sc.values() if r["tag"] == "harness")
        forced = sum(1 for r in sc.values() if str(r.get("forced_finish")).lower() in ("true", "1"))
        cost = sum(float(r.get("cost_usd") or 0) for r in sc.values())
        prov = bs.get("git_describe") or ("sha " + (bs.get("harness_sha256") or "")[:12])
        L.append(f"| {run} | {bs.get('started_at', '')[:16]} | {bs.get('model')} | {bs.get('thinking_level')} | {prov} | "
                 f"{st.mean(dice):.3f} | {st.median(dice):.3f} | {st.mean(dl) if dl else float('nan'):.3f} | {len(loc)} | "
                 f"{len(sc) - len(loc)} | {st.mean(tc):.2f} | {st.mean(mp):.2f} | {herr} | {forced} | {cost:.2f} |")
    L.append("")
    if runs:
        L += ["### Per-histotype mean Dice", "", "| run | " + " | ".join(HTYPES) + " |", "|---|" + "---|" * 5]
        for run in runs:
            cells = []
            for h in HTYPES:
                v = [float(r["dice"]) for r in data[run].values() if r["histotype"] == h]
                cells.append(f"{st.mean(v):.3f}")
            L.append(f"| {run} | " + " | ".join(cells) + " |")
        L.append(f"| one-click (oracle) | " + " | ".join(
            f"{st.mean([float(r['dice_all']) for r in oc.values() if r['histotype'] == h]):.3f}" for h in HTYPES) + " |")
        L.append("| published U-Net | " + " | ".join(f"{UNET[h]:.3f}" for h in HTYPES) + " |")
        L += ["", "### Per-case final Dice (✗ = first positive click not inside GT and Dice < 0.5, i.e. tag `localization`)", "",
              "| case | one-click | " + " | ".join(runs) + " |", "|---|---|" + "---|" * len(runs)]
        for c in cases:
            cells = []
            for run in runs:
                r = data[run].get(c["case"])
                if not r:
                    cells.append("–")
                    continue
                mark = " ✗" if r["tag"] == "localization" else ""
                cells.append(f"{float(r['dice']):.3f}{mark}")
            L.append(f"| {c['case']} | {f3(oc.get(c['case'], {}).get('dice_all'))} | " + " | ".join(cells) + " |")
        L += ["", "### Per-case tool calls / model prompts", "", "| case | " + " | ".join(runs) + " |", "|---|" + "---|" * len(runs)]
        for c in cases:
            cells = [f"{data[r][c['case']]['n_tool_calls']}/{data[r][c['case']]['n_model_prompts']}" if c["case"] in data[r] else "–"
                     for r in runs]
            L.append(f"| {c['case']} | " + " | ".join(cells) + " |")
        L.append("")
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
